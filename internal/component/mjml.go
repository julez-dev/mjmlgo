var ErrMJMLBadlyFormatted = errors.New("MJML badly formatted")

type MJML struct{}

func (m MJML) Name() string {
	return "mjml"
}

func (m MJML) AllowedAttributes() map[string]validateAttributeFunc {
	return map[string]validateAttributeFunc{
		"owa":  validateEnum([]string{"desktop"}),
		"lang": validateType("string"),
		"dir":  validateEnum([]string{"ltr", "rtl", "auto"}),
	}
}

func (m MJML) DefaultAttributes(_ *RenderContext) map[string]string {
	return map[string]string{
		"dir":  "auto",
		"lang": "und",
	}
}

func (m MJML) Render(ctx *RenderContext, w io.Writer, n *node.Node) error {
	if len(n.Children) < 1 {
		return fmt.Errorf("%w: no children in <mjml> tag", ErrMJMLBadlyFormatted)
	}

	hasBody := slices.ContainsFunc(n.Children, func(node *node.Node) bool {
		return node.Type == BodyTagName
	})

	if !hasBody {
		return fmt.Errorf("%w: no <mj-body> in <mjml> tag", ErrMJMLBadlyFormatted)
	}

	if err := m.validateHTMLAttributeTags(n, nil); err != nil {
		return err
	}

	ctx.Language = n.GetAttributeValueDefault("lang")
	ctx.ForceOWADesktop = n.GetAttributeValueDefault("owa") == "desktop"

	if err := templates.ExecuteTemplate(w, "html-start-tag.tmpl", map[string]string{
		"lang": n.GetAttributeValueDefault("lang"),
		"dir":  n.GetAttributeValueDefault("dir"),
	}); err != nil {
		return err
	}

	ctx.Direction = n.GetAttributeValueDefault("dir")
	ctx.Breakpoint = "480px"
	ctx.IncludeMobileFullWidthStyle = hasNodeType(n, "mj-image")

	var headNode *node.Node

	var headTextBuilder strings.Builder
	var bodyTextBuilder strings.Builder
	var resultTextBuilder strings.Builder

	for _, child := range n.Children {
		switch child.Type {
		case HeadTagName:
			if err := m.preparseHeadMetaValues(ctx, child); err != nil {
				return err
			}

			headNode = child
		case BodyTagName:
			m.setAttributeDefaults(ctx, child, "")
			body := MJMLBody{}
			if err := InitComponent(ctx, body, child); err != nil {
				return err
			}
			if err := body.Render(ctx, &bodyTextBuilder, child); err != nil {
				return err
			}
		}
	}

	ctx.BodyContent = bodyTextBuilder.String()

	// render head as last element, because there a custom MJML styles generated by rendering other components
	var head MJMLHead
	if err := head.Render(ctx, &headTextBuilder, headNode); err != nil {
		return fmt.Errorf("error rendering <mj-head>: %w", err)
	}

	resultTextBuilder.Grow(len(headTextBuilder.String()) + len(bodyTextBuilder.String()))
	_, _ = resultTextBuilder.WriteString(headTextBuilder.String())
	_, _ = resultTextBuilder.WriteString(bodyTextBuilder.String())

	_, _ = io.WriteString(w, resultTextBuilder.String())
	_, _ = io.WriteString(w, "</html>")

	return nil
}

// setAttributeDefaults applies the <mj-attributes> cascade to the body tree.
// Layers are applied from lowest to highest precedence: <mj-all>, per-tag
// defaults, <mj-class> attributes, per-tag defaults declared inside an
// ancestor's <mj-class>, and finally attributes written on the element itself.
func (m MJML) setAttributeDefaults(ctx *RenderContext, n *node.Node, parentMjClasses string) {
	if !strings.HasPrefix(n.Type, "mj-") {
		return
	}

	ownMjClasses, hasOwnMjClasses := n.GetAttributeValue("mj-class")
	nextParentMjClasses := parentMjClasses
	if hasOwnMjClasses && ownMjClasses != "" {
		nextParentMjClasses = ownMjClasses
	}

	combined := make(AttributeMap)

	mergeAttributes(combined, ctx.AttributeDefaults[AllTagName])
	mergeAttributes(combined, ctx.AttributeDefaults[n.Type])
	mergeAttributes(combined, classAttributes(ctx, ownMjClasses))
	mergeAttributes(combined, classDefaultsForTag(ctx, parentMjClasses, n.Type))

	for name, value := range combined {
		if name == "mj-class" {
			continue
		}

		if _, has := n.GetAttributeValue(name); !has {
			n.SetAttribute(name, value)
		}
	}

	for _, child := range n.Children {
		m.setAttributeDefaults(ctx, child, nextParentMjClasses)
	}
}

// classAttributes resolves a space-separated mj-class list. Later classes
// override earlier ones; css-class values are concatenated instead of replacing
// each other, matching MJML's applyAttributes.
func classAttributes(ctx *RenderContext, mjClasses string) AttributeMap {
	combined := make(AttributeMap)

	for _, name := range strings.Split(mjClasses, " ") {
		if name == "" {
			continue
		}

		class, exists := ctx.Classes[name]
		if !exists {
			continue
		}

		cssClass, hasCSSClass := combined["css-class"]
		classCSSClass, classHasCSSClass := class["css-class"]

		mergeAttributes(combined, class)

		if hasCSSClass && classHasCSSClass {
			combined["css-class"] = cssClass + " " + classCSSClass
		}
	}

	return combined
}

// classDefaultsForTag resolves the per-tag defaults declared inside the
// <mj-class> elements that apply to an element through its ancestors.
func classDefaultsForTag(ctx *RenderContext, mjClasses, tagName string) AttributeMap {
	combined := make(AttributeMap)

	for _, name := range strings.Split(mjClasses, " ") {
		if name == "" {
			continue
		}

		defaults, exists := ctx.ClassDefaults[name]
		if !exists {
			continue
		}

		mergeAttributes(combined, defaults[tagName])
	}

	return combined
}

func mergeAttributes(dst, src AttributeMap) {
	for name, value := range src {
		dst[name] = value
	}
}

func attributesToMap(attributes []xml.Attr) AttributeMap {
	m := make(AttributeMap, len(attributes))
	for _, attribute := range attributes {
		m[attribute.Name.Local] = attribute.Value
	}

	return m
}

// validateHTMLAttributeTags enforces the fixed nesting of the mj-html-attributes
// family and rejects missing selector paths or attribute names.
func (m MJML) validateHTMLAttributeTags(n, parent *node.Node) error {
	parentType := ""
	if parent != nil {
		parentType = parent.Type
	}

	switch n.Type {
	case HTMLAttributesTagName:
		if parentType != HeadTagName {
			return fmt.Errorf("%w: <mj-html-attributes> must be a direct child of <mj-head>", ErrValidation)
		}
	case SelectorTagName:
		if parentType != HTMLAttributesTagName {
			return fmt.Errorf("%w: <mj-selector> must be a direct child of <mj-html-attributes>", ErrValidation)
		}

		path, has := n.GetAttributeValue("path")
		if !has || strings.TrimSpace(path) == "" {
			return fmt.Errorf("%w: missing path in mj-selector element", ErrValidation)
		}
	case HTMLAttributeTagName:
		if parentType != SelectorTagName {
			return fmt.Errorf("%w: <mj-html-attribute> must be a direct child of <mj-selector>", ErrValidation)
		}

		name, has := n.GetAttributeValue("name")
		if !has || strings.TrimSpace(name) == "" {
			return fmt.Errorf("%w: missing name in mj-html-attribute element", ErrValidation)
		}
	}

	for _, child := range n.Children {
		if err := m.validateHTMLAttributeTags(child, n); err != nil {
			return err
		}
	}

	return nil
}

func (m MJML) preparseHeadMetaValues(ctx *RenderContext, n *node.Node) error {
	ctx.ensureFontRegistry()

	for _, child := range n.Children {
		switch child.Type {
		case HTMLAttributesTagName:
			for _, selector := range child.Children {
				path, _ := selector.GetAttributeValue("path")

				for _, htmlAttribute := range selector.Children {
					if htmlAttribute.Type != HTMLAttributeTagName {
						continue
					}

					name, _ := htmlAttribute.GetAttributeValue("name")
					ctx.addHTMLAttribute(path, name, htmlAttribute.Content)
				}
			}
		case AttributesTagName:
			for _, nestedChild := range child.Children {
				switch nestedChild.Type {
				case ClassTagName:
					name, has := nestedChild.GetAttributeValue("name")
					if !has {
						return fmt.Errorf("%w: missing name in mj-class element", ErrValidation)
					}

					attributes := attributesToMap(nestedChild.Attributes)
					delete(attributes, "name")

					if ctx.Classes == nil {
						ctx.Classes = make(map[string]AttributeMap)
					}

					if ctx.Classes[name] == nil {
						ctx.Classes[name] = make(AttributeMap)
					}

					mergeAttributes(ctx.Classes[name], attributes)

					if ctx.ClassDefaults == nil {
						ctx.ClassDefaults = make(map[string]map[string]AttributeMap)
					}

					if ctx.ClassDefaults[name] == nil {
						ctx.ClassDefaults[name] = make(map[string]AttributeMap)
					}

					for _, tagDefault := range nestedChild.Children {
						if ctx.ClassDefaults[name][tagDefault.Type] == nil {
							ctx.ClassDefaults[name][tagDefault.Type] = make(AttributeMap)
						}

						mergeAttributes(ctx.ClassDefaults[name][tagDefault.Type], attributesToMap(tagDefault.Attributes))
					}
				default:
					m.mergeAttributeDefaults(ctx, nestedChild)
				}
			}
		case BreakpointTagName:
			if p, found := child.GetAttributeValue("width"); found {
				ctx.Breakpoint = p
			}
		case PreviewTagName:
			ctx.PreviewText = child.Content
		case TitleTagName:
			ctx.Title = child.Content
		case FontTagName:
			n, has := child.GetAttributeValue("name")
			if !has {
				return fmt.Errorf("%w: missing name in mj-font element", ErrValidation)
			}

			ctx.addFont(n, child.GetAttributeValueDefault("href"))
		}
	}

	return nil
}

func (m MJML) mergeAttributeDefaults(ctx *RenderContext, n *node.Node) {
	if ctx.AttributeDefaults == nil {
		ctx.AttributeDefaults = make(map[string]AttributeMap)
	}

	if ctx.AttributeDefaults[n.Type] == nil {
		ctx.AttributeDefaults[n.Type] = make(AttributeMap)
	}

	mergeAttributes(ctx.AttributeDefaults[n.Type], attributesToMap(n.Attributes))
}

func hasNodeType(n *node.Node, t string) bool {
	if n.Type == t {
		return true
	}
	for _, child := range n.Children {
		if hasNodeType(child, t) {
			return true
		}
	}
	return false
}
